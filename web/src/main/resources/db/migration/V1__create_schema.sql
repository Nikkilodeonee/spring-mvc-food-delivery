CREATE TABLE customer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name       VARCHAR(255) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    name            VARCHAR(255),
    balance         NUMERIC(19, 2)
);

CREATE UNIQUE INDEX idx_customer_user_name ON customer (user_name);

CREATE TABLE food (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    description     VARCHAR(500),
    calorie         NUMERIC(19, 2),
    price           NUMERIC(19, 2)
);

CREATE TABLE _order (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price               NUMERIC(19, 2),
    timestamp_created   TIMESTAMP,
    customer_id         BIGINT NOT NULL,
    CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE order_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pieces      INT NOT NULL,
    price       NUMERIC(19, 2),
    food_id     BIGINT NOT NULL,
    order_id    BIGINT NOT NULL,
    CONSTRAINT fk_order_item_food FOREIGN KEY (food_id) REFERENCES food (id),
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES _order (id)
);
